-- WORDORA 2.0: ONE-TIME SUPABASE SETUP.
-- Run the COMPLETE setup.sql from Supabase Dashboard > SQL Editor.
-- Safe to re-run: seed rows are not duplicated. Existing account data is retained.
-- No service-role keys are required by the website.

create table if not exists public.words (
  id bigint generated by default as identity primary key,
  owner_id uuid references auth.users(id) on delete cascade,
  category text not null check (category in ('daily','verbs','food','travel','feelings','study','nature','technology','mine')),
  en text not null check (length(btrim(en)) between 1 and 80),
  uz text not null check (length(btrim(uz)) between 1 and 120),
  example_en text not null default '' check (length(example_en) <= 240),
  example_uz text not null default '' check (length(example_uz) <= 240),
  level text not null default 'A1',
  created_at timestamptz not null default now(),
  constraint wordora_word_owner_category check (
    (owner_id is null and category <> 'mine') or
    (owner_id is not null and category = 'mine')
  )
);
create unique index if not exists wordora_words_personal_unique
  on public.words (owner_id, lower(en)) where owner_id is not null;
create index if not exists wordora_words_category on public.words(category);
create index if not exists wordora_words_owner on public.words(owner_id);

create table if not exists public.progress (
  user_id uuid not null references auth.users(id) on delete cascade,
  word_id bigint not null references public.words(id) on delete cascade,
  ease numeric(5,3) not null default 2.500,
  interval_days integer not null default 0,
  repetitions integer not null default 0,
  due_on date not null,
  correct_count integer not null default 0,
  wrong_count integer not null default 0,
  last_reviewed date,
  primary key (user_id, word_id)
);
create index if not exists wordora_progress_due on public.progress(user_id,due_on);

create table if not exists public.reviews (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  word_id bigint not null references public.words(id) on delete cascade,
  mode text not null check (mode in ('cards','choice','write','listen')),
  quality integer not null check (quality between 0 and 5),
  correct boolean not null,
  reviewed_at timestamptz not null default now(),
  reviewed_on date not null
);
create index if not exists wordora_reviews_user_day on public.reviews(user_id,reviewed_on);

alter table public.words enable row level security;
alter table public.progress enable row level security;
alter table public.reviews enable row level security;

-- Explicit grants: anonymous visitors cannot read the dictionary.
revoke all on public.words, public.progress, public.reviews from public, anon, authenticated;
grant select, insert, delete on public.words to authenticated;
grant select on public.progress, public.reviews to authenticated;
-- Identity sequences need not be exposed to anonymous clients.

drop policy if exists "wordora_read_visible_words" on public.words;
create policy "wordora_read_visible_words" on public.words for select to authenticated
  using (owner_id is null or owner_id = (select auth.uid()));
drop policy if exists "wordora_create_own_word" on public.words;
create policy "wordora_create_own_word" on public.words for insert to authenticated
  with check (owner_id = (select auth.uid()) and category = 'mine');
drop policy if exists "wordora_delete_own_word" on public.words;
create policy "wordora_delete_own_word" on public.words for delete to authenticated
  using (owner_id = (select auth.uid()));

drop policy if exists "wordora_read_own_progress" on public.progress;
create policy "wordora_read_own_progress" on public.progress for select to authenticated
  using (user_id = (select auth.uid()));
drop policy if exists "wordora_read_own_reviews" on public.reviews;
create policy "wordora_read_own_reviews" on public.reviews for select to authenticated
  using (user_id = (select auth.uid()));

-- Rate-limit per-user personal vocabulary size at the database layer.
create or replace function public.wordora_word_limit()
returns trigger language plpgsql security invoker set search_path = '' as $$
begin
  if new.owner_id is not null and
     (select count(*) from public.words where owner_id = new.owner_id) >= 5000 then
    raise exception 'Shaxsiy lug‘at uchun 5000 so‘z chegarasi bor';
  end if;
  return new;
end;
$$;
drop trigger if exists trg_wordora_word_limit on public.words;
create trigger trg_wordora_word_limit before insert on public.words
  for each row execute function public.wordora_word_limit();
revoke all on function public.wordora_word_limit() from public, anon, authenticated;

-- Only authenticated users can read their own statistics.
create or replace function public.wordora_stats()
returns jsonb language plpgsql stable security invoker set search_path = '' as $$
declare
  v_user uuid := auth.uid();
  v_today date := (now() at time zone 'Asia/Tashkent')::date;
  v_cursor date;
  v_streak integer := 0;
  v_total integer;
  v_learned integer;
  v_started integer;
  v_due integer;
  v_today_reviews integer;
  v_activity jsonb;
begin
  if v_user is null then raise exception 'Kirish talab qilinadi' using errcode='42501'; end if;
  select count(*) into v_total from public.words w
    where w.owner_id is null or w.owner_id = v_user;
  select count(*) into v_learned from public.progress p
    where p.user_id=v_user and p.repetitions>=2;
  select count(*) into v_started from public.progress p where p.user_id=v_user;
  select count(*) into v_due from public.progress p
    where p.user_id=v_user and p.due_on <= v_today;
  select count(*) into v_today_reviews from public.reviews r
    where r.user_id=v_user and r.reviewed_on=v_today;
  v_cursor := v_today;
  if v_today_reviews=0 then v_cursor:=v_today-1; end if;
  while exists (select 1 from public.reviews r
                where r.user_id=v_user and r.reviewed_on=v_cursor) loop
    v_streak:=v_streak+1;
    v_cursor:=v_cursor-1;
  end loop;
  select coalesce(jsonb_agg(jsonb_build_object(
    'date',(v_today-g.off)::text,
    'count',(select count(*) from public.reviews r where r.user_id=v_user and r.reviewed_on=v_today-g.off)
  ) order by g.off desc),'[]'::jsonb) into v_activity
    from generate_series(0,6) as g(off);
  return jsonb_build_object(
    'total',v_total,'learned',v_learned,'started',v_started,
    'due',v_due,'practiced_today',v_today_reviews,'streak',v_streak,
    'activity',v_activity,'daily_goal',15);
end;
$$;

-- Return due words before new ones; never study words scheduled for the future.
create or replace function public.wordora_session(
  p_category text default 'all', p_limit integer default 10
) returns jsonb language plpgsql stable security invoker set search_path = '' as $$
declare
  v_user uuid := auth.uid();
  v_today date := (now() at time zone 'Asia/Tashkent')::date;
  v_rows jsonb;
  v_total integer;
begin
  if v_user is null then raise exception 'Kirish talab qilinadi' using errcode='42501'; end if;
  if p_category not in ('all','daily','verbs','food','travel','feelings','study','nature','technology','mine')
    or p_category is null then
    raise exception 'Noma’lum mavzu';
  end if;
  if p_limit < 1 or p_limit > 30 or p_limit is null then raise exception 'Limit 1 dan 30 gacha'; end if;
  select count(*) into v_total
    from public.words w left join public.progress p on p.word_id=w.id and p.user_id=v_user
   where (w.owner_id is null or w.owner_id=v_user)
     and (p_category='all' or (p_category='mine' and w.owner_id=v_user) or w.category=p_category)
     and (p.due_on is null or p.due_on <= v_today);
  select coalesce(jsonb_agg(
           to_jsonb(x) - 'sort_group' - 'sort_due' - 'sort_misses'
           order by x.sort_group, x.sort_due, x.sort_misses desc, x.id
         ), '[]'::jsonb) into v_rows
  from (
    select w.id,w.owner_id,w.category,w.en,w.uz,w.example_en,w.example_uz,w.level,
           p.repetitions,p.due_on,p.correct_count,p.wrong_count,p.interval_days,
           case when p.due_on is null then 1 else 0 end as sort_group,
           coalesce(p.due_on,v_today) as sort_due,
           coalesce(p.wrong_count,0) as sort_misses
    from public.words w left join public.progress p on p.word_id=w.id and p.user_id=v_user
    where (w.owner_id is null or w.owner_id=v_user)
      and (p_category='all' or (p_category='mine' and w.owner_id=v_user) or w.category=p_category)
      and (p.due_on is null or p.due_on <= v_today)
    order by sort_group,sort_due,sort_misses desc,w.id
    limit p_limit
  ) x;
  return jsonb_build_object('words',v_rows,'remaining',greatest(0,v_total-jsonb_array_length(v_rows)));
end;
$$;

-- A narrowly-scoped RPC is the ONLY public path that writes learning progress.
-- Security definer is necessary because browser clients have NO INSERT/UPDATE
-- grants on progress or reviews. User ID always comes from auth.uid(), never
-- from a client argument. Object names are fully qualified; search_path is fixed.
create or replace function public.wordora_review(
  p_word_id bigint, p_mode text, p_quality integer
) returns jsonb language plpgsql volatile security definer set search_path = '' as $$
declare
  v_user uuid := auth.uid();
  v_today date := (now() at time zone 'Asia/Tashkent')::date;
  v_prev public.progress%rowtype;
  v_ease numeric := 2.5;
  v_interval integer := 0;
  v_reps integer := 0;
  v_due date;
  v_correct boolean;
begin
  if v_user is null then raise exception 'Kirish talab qilinadi' using errcode='42501'; end if;
  if p_mode is null or p_mode not in ('cards','choice','write','listen') or
     p_quality is null or p_quality < 0 or p_quality > 5 then
    raise exception 'Mashq natijasi noto‘g‘ri';
  end if;
  if not exists (select 1 from public.words w where w.id=p_word_id
      and (w.owner_id is null or w.owner_id=v_user)) then
    raise exception 'So‘z topilmadi yoki ruxsat yo‘q' using errcode='42501';
  end if;
  select * into v_prev from public.progress
    where user_id=v_user and word_id=p_word_id for update;
  if found then
    v_ease:=v_prev.ease;
    v_interval:=v_prev.interval_days;
    v_reps:=v_prev.repetitions;
  end if;
  if p_quality<3 then
    v_reps:=0;
    v_interval:=1;
  else
    v_reps:=v_reps+1;
    if v_reps=1 then v_interval:=1;
    elsif v_reps=2 then v_interval:=3;
    else v_interval:=greatest(1,round(v_interval::numeric*v_ease)::integer);
    end if;
  end if;
  v_ease:=least(9.0,greatest(1.3,v_ease+(0.1-(5-p_quality)*(0.08+(5-p_quality)*0.02))));
  v_due:=v_today+v_interval;
  v_correct:=(p_quality>=3);
  insert into public.progress(user_id,word_id,ease,interval_days,repetitions,due_on,
                              correct_count,wrong_count,last_reviewed)
    values(v_user,p_word_id,v_ease,v_interval,v_reps,v_due,
           case when v_correct then 1 else 0 end,
           case when v_correct then 0 else 1 end,v_today)
    on conflict(user_id,word_id) do update set
      ease=excluded.ease,interval_days=excluded.interval_days,
      repetitions=excluded.repetitions,due_on=excluded.due_on,
      correct_count=public.progress.correct_count+excluded.correct_count,
      wrong_count=public.progress.wrong_count+excluded.wrong_count,
      last_reviewed=excluded.last_reviewed;
  insert into public.reviews(user_id,word_id,mode,quality,correct,reviewed_on)
    values (v_user,p_word_id,p_mode,p_quality,v_correct,v_today);
  return jsonb_build_object('ok',true,'next_review',v_due::text,
                            'interval_days',v_interval,'correct',v_correct);
end;
$$;

