-- WORDORA 5.0: user-defined Unit/book collections, independent of fixed topic and POS.
-- Run in the EXISTING Wordora Supabase project AFTER upgrade_4_0.sql.
-- ADDITIVE ONLY: does not delete or modify words/progress/reviews/word_learning.
-- Repeatable. Never run setup.sql again.
begin;

create table if not exists public.word_collections (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  name text not null check (char_length(btrim(name)) between 1 and 80),
  created_at timestamptz not null default now(),
  unique(id,user_id)
);
create unique index if not exists wordora_collection_names_unique
  on public.word_collections(user_id,lower(btrim(name)));
create index if not exists wordora_collections_owner
  on public.word_collections(user_id,created_at);

-- One word can appear in multiple Unit(s), without copying its text or its learning data.
create table if not exists public.word_collection_items (
  user_id uuid not null references auth.users(id) on delete cascade,
  collection_id bigint not null,
  word_id bigint not null references public.words(id) on delete cascade,
  added_at timestamptz not null default now(),
  primary key(user_id,collection_id,word_id),
  constraint wordora_collection_item_owner foreign key(collection_id,user_id)
    references public.word_collections(id,user_id) on delete cascade
);
create index if not exists wordora_collection_items_by_word
  on public.word_collection_items(user_id,word_id);

alter table public.word_collections enable row level security;
alter table public.word_collection_items enable row level security;
revoke all on public.word_collections from public,anon,authenticated;
revoke all on public.word_collection_items from public,anon,authenticated;
grant select,insert,update,delete on public.word_collections to authenticated;
grant select,insert,delete on public.word_collection_items to authenticated;
grant usage,select on sequence public.word_collections_id_seq to authenticated;

-- Owned collections are invisible to other users.
drop policy if exists wordora_collections_read on public.word_collections;
create policy wordora_collections_read on public.word_collections
for select to authenticated using(user_id=(select auth.uid()));
drop policy if exists wordora_collections_add on public.word_collections;
create policy wordora_collections_add on public.word_collections
for insert to authenticated with check(user_id=(select auth.uid()));
drop policy if exists wordora_collections_edit on public.word_collections;
create policy wordora_collections_edit on public.word_collections
for update to authenticated using(user_id=(select auth.uid()))
with check(user_id=(select auth.uid()));
drop policy if exists wordora_collections_delete on public.word_collections;
create policy wordora_collections_delete on public.word_collections
for delete to authenticated using(user_id=(select auth.uid()));

-- Membership is allowed for PUBLIC starter words or the user's own personal words.
drop policy if exists wordora_items_read on public.word_collection_items;
create policy wordora_items_read on public.word_collection_items
for select to authenticated using(user_id=(select auth.uid()));
drop policy if exists wordora_items_add on public.word_collection_items;
create policy wordora_items_add on public.word_collection_items
for insert to authenticated with check(
  user_id=(select auth.uid())
  and exists(select 1 from public.words w where w.id=word_id
     and (w.owner_id is null or w.owner_id=(select auth.uid())))
);
drop policy if exists wordora_items_delete on public.word_collection_items;
create policy wordora_items_delete on public.word_collection_items
for delete to authenticated using(user_id=(select auth.uid()));

-- Starter examples: 'run' belongs to Sport while still being a verb.
-- Only change the default starter categorization, NEVER a user's edited tags.
update public.words set topic='sports',word_type='verb'
where owner_id is null and lower(btrim(en)) in ('run','jump','swim','running')
  and topic in ('verbs','other','sports');

commit;
notify pgrst, 'reload schema';
-- Expected: Success. No rows returned.